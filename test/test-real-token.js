import http from 'http';
import fs from 'fs';
import path from 'path';
import assert from 'assert';
import { spawn } from 'child_process';

console.log('Starting Real Token & End-to-End Inference Server Verification...');

// Start H2O Inference Server
const serverProcess = spawn('node', ['src/h2o-copilot-server.js'], {
  env: { ...process.env, DEBUG: 'true' },
  stdio: 'pipe'
});

let serverStarted = false;
let activePort = null;

serverProcess.stdout.on('data', (data) => {
  const output = data.toString();
  const match = output.match(/Running on http:\/\/localhost:(\d+)/);
  if (match) {
    activePort = parseInt(match[1], 10);
    serverStarted = true;
  }
});

serverProcess.stderr.on('data', (data) => {});

function makeRequest(port, method, path, headers = {}, body = null) {
  return new Promise((resolve, reject) => {
    const dataStr = body ? JSON.stringify(body) : '';
    const req = http.request({
      hostname: 'localhost',
      port: port,
      path: path,
      method: method,
      headers: {
        'Content-Type': 'application/json',
        'Content-Length': Buffer.byteLength(dataStr),
        ...headers
      }
    }, (res) => {
      let responseBody = '';
      res.on('data', chunk => responseBody += chunk);
      res.on('end', () => {
        try {
          resolve({
            statusCode: res.statusCode,
            body: responseBody ? JSON.parse(responseBody) : null
          });
        } catch (e) {
          resolve({ statusCode: res.statusCode, body: responseBody });
        }
      });
    });

    req.on('error', reject);
    if (dataStr) req.write(dataStr);
    req.end();
  });
}

async function runRealTokenTest() {
  let attempts = 0;
  while (!serverStarted && attempts < 30) {
    await new Promise(r => setTimeout(r, 200));
    attempts++;
  }

  if (!serverStarted || !activePort) {
    console.error('Server failed to start.');
    serverProcess.kill();
    process.exit(1);
  }

  console.log(`[Verified Server Port]: ${activePort}`);

  // Read the exact real instance access key generated by H2O
  const keyFilePath = path.resolve(process.cwd(), '.h2o-instance-key');
  assert(fs.existsSync(keyFilePath), 'Instance access key file must exist.');
  const realToken = fs.readFileSync(keyFilePath, 'utf8').trim();
  console.log(`[Loaded Real Generated Token]: ${realToken}`);

  // Test 1: OpenAI-compatible /v1/chat/completions with real generated token
  console.log('\n--- TESTING POST /v1/chat/completions with Real Token ---');
  const chatRes = await makeRequest(activePort, 'POST', '/v1/chat/completions', {
    'Authorization': `Bearer ${realToken}`
  }, {
    model: 'gemini-4-hydrogen',
    messages: [
      { role: 'user', content: 'Provide system metrics telemetry.' }
    ]
  });

  console.log('Status Code:', chatRes.statusCode);
  console.log('Response Body:', JSON.stringify(chatRes.body, null, 2));
  assert.strictEqual(chatRes.statusCode, 200);
  assert.strictEqual(chatRes.body.object, 'chat.completion');
  assert(chatRes.body.choices[0].message.content.length > 0);

  // Test 2: Native /v1/copilot with real generated token
  console.log('\n--- TESTING POST /v1/copilot with Real Token ---');
  const copilotRes = await makeRequest(activePort, 'POST', '/v1/copilot', {
    'Authorization': `Bearer ${realToken}`
  }, {
    messages: [
      { role: 'user', content: 'Give status report.' }
    ]
  });

  console.log('Status Code:', copilotRes.statusCode);
  console.log('Response Body:', JSON.stringify(copilotRes.body, null, 2));
  assert.strictEqual(copilotRes.statusCode, 200);
  assert.strictEqual(copilotRes.body.role, 'assistant');
  assert(copilotRes.body.content.length > 0);

  console.log('\n==================================================');
  console.log('REAL GENERATED TOKEN VERIFIED: 100% SUCCESSFUL!');
  console.log('==================================================');

  serverProcess.kill();
  process.exit(0);
}

runRealTokenTest().catch(err => {
  console.error('Real token test failed:', err);
  serverProcess.kill();
  process.exit(1);
});
